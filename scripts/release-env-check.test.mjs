test('CLI does not overwrite input/reports, leak secrets, or execute env contents', () => {
  const dir = mkdtempSync(join(tmpdir(), 'massajoy-env-check-'));
  try {
    const input = join(dir, 'release.env'), report = join(dir, 'report.json');
    const text = Object.entries(base()).map(([k, v]) => `${k}=${v}`).join('\n');
    writeFileSync(input, text);
    const run = args => spawnSync(process.execPath, [fileURLToPath(new URL('./release-env-check.mjs', import.meta.url)), ...args], { encoding: 'utf8' });
    let result = run(['--env-file', input, '--report', report]);
    assert.equal(result.status, 0, result.stderr);
    assert.equal(JSON.parse(readFileSync(report, 'utf8')).deploymentReady, false);
    assert.equal((result.stdout + result.stderr).includes(base().JWT_SECRET), false);
    assert.equal((result.stdout + result.stderr).includes(vaultKey), false);
    assert.equal(run(['--env-file', input, '--report', input]).status, 1);
    assert.equal(run(['--env-file', input, '--report', report]).status, 1);
    assert.equal(readFileSync(input, 'utf8'), text);
    writeFileSync(input, 'JWT_SECRET=$(touch should-not-run)');
    result = run(['--env-file', input]);
    assert.equal(result.status, 1);
    assert.equal((result.stdout + result.stderr).includes('touch'), false);
    assert.equal(run(['--env-file', input, '--unknown']).status, 1);
  } finally {
    assert.equal(dirname(resolve(dir)), resolve(tmpdir()));
    assert.ok(basename(dir).startsWith('massajoy-env-check-'));
    rmSync(dir, { recursive: true, force: true });
  }
});
