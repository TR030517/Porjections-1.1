test('production vault key requires canonical base64 of exactly 32 bytes without exposing values', () => {
  const invalid = ['', undefined, 'REPLACE_WITH_VAULT_KEY', Buffer.alloc(31, 7).toString('base64'), Buffer.alloc(33, 7).toString('base64'), vaultKey.slice(0, -1), vaultKey + '\n', vaultKey.slice(0, -2) + 'B='];
  for (const value of invalid) {
    const result = validateReleaseEnvironment({ ...base(), MERCHANT_CREDENTIAL_VAULT_KEY: value });
    assert.ok(result.checks.some(check => check.id === 'credential_vault.key_base64_32_bytes' && check.status === 'fail'));
    if (value) assert.equal(JSON.stringify(result).includes(value), false);
  }
  const result = validateReleaseEnvironment(base());
  assert.equal(result.configurationValid, true);
  assert.equal(JSON.stringify(result).includes(vaultKey), false);
  assert.ok(result.unverified.includes('Credential vault key continuity and existing-envelope decryption'));
});

