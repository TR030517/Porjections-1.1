test('parser permits literal quotes and comments but rejects ambiguity and executable syntax', () => {
  assert.deepEqual({ ...parseEnvironment('\uFEFFA="literal"\r\nB=plain # comment\nC=\'quoted\'\n# ignored\n') }, { A: 'literal', B: 'plain', C: 'quoted' });
  for (const text of ['A=one\nA=two', 'export A=one', 'A="unterminated', 'A=$(echo bad)', 'A=${OTHER}', 'A=`echo bad`', 'A=abc\u0000def']) assert.throws(() => parseEnvironment(text), /^Error: ENV_/);
  assert.throws(() => parseEnvironment('A=' + 'x'.repeat(65536)), /ENV_FILE_TOO_LARGE/);
});
