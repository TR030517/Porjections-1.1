test('fresh loopback settings generated by local:env pass local preflight', () => {
  const dir = mkdtempSync(join(tmpdir(), 'massajoy-local-env-'));
  try {
    const generator = fileURLToPath(new URL('./create-local-env.mjs', import.meta.url));
    const generated = spawnSync(process.execPath, [generator], { cwd: dir, encoding: 'utf8' });
    assert.equal(generated.status, 0, generated.stderr);
    const raw = readFileSync(join(dir, '.local', 'compose.env'), 'utf8');
    const environment = parseEnvironment(raw);
    const report = validateReleaseEnvironment(environment, { local: true });
    assert.equal(report.configurationValid, true, JSON.stringify(report.checks.filter(check => check.status === 'fail')));
    assert.equal(environment.NOTIFICATION_WORKER_ENABLED, 'true');
    assert.equal(report.orderEmail.enabled, false);
    assert.equal(spawnSync(process.execPath, [generator], { cwd: dir }).status, 0);
    assert.ok(readFileSync(join(dir, '.local', 'compose.env'), 'utf8') === raw, 'Rerunning local:env must preserve the existing settings');
  } finally {
    assert.equal(dirname(resolve(dir)), resolve(tmpdir()));
    assert.ok(basename(dir).startsWith('massajoy-local-env-'));
    rmSync(dir, { recursive: true, force: true });
  }
});

