/// MJAPP — Firebase Cloud Messaging Service (Flutter side)
///
/// Handles FCM token registration, push notification handling, and
/// graceful degradation on unsupported platforms (e.g., web without
/// Firebase config, or mobile without native setup).
///
/// In development / mock mode, all operations silently log instead
/// of throwing.
library;

import 'dart:developer' as developer;
import 'package:firebase_core/firebase_core.dart';
import 'package:firebase_messaging/firebase_messaging.dart';
import 'package:dio/dio.dart';

class FcmService {
  static final FirebaseMessaging _messaging = FirebaseMessaging.instance;
  static bool _initialized = false;

  /// Initialise Firebase and FCM.  Catches any configuration errors so
  /// the app can still run without Firebase setup.
  static Future<void> init() async {
    if (_initialized) return;

    try {
      // For web, Firebase.initializeApp needs a firebase_options.dart
      // generated by `flutterfire configure`.  Without it, the call
      // will throw — catch gracefully below.
      await Firebase.initializeApp();
      _initialized = true;
      developer.log('FCM: Firebase initialized', name: 'FcmService');
    } catch (_) {
      developer.log(
        'FCM: Firebase init skipped — app runs without push.',
        name: 'FcmService',
      );
      return;
    }

    try {
      // Request notification permission
      final permission = await _messaging.requestPermission(
        alert: true,
        badge: true,
        sound: true,
      );

      if (permission.authorizationStatus == AuthorizationStatus.denied) {
        developer.log(
          'FCM: Notification permission denied.',
          name: 'FcmService',
        );
        return;
      }

      // Check token availability without logging the device token.
      final token = await _messaging.getToken();
      developer.log(
        token == null ? 'FCM: Token unavailable' : 'FCM: Token obtained',
        name: 'FcmService',
      );

      // Listen for foreground messages
      FirebaseMessaging.onMessage.listen(_handleForegroundMessage);

      // Listen for notification taps that open the app from background
      FirebaseMessaging.onMessageOpenedApp.listen(_handleNotificationTap);

      // Handle cold-start (app opened from killed state via notification)
      final initialMessage = await _messaging.getInitialMessage();
      if (initialMessage != null) {
        _handleNotificationTap(initialMessage);
      }

      developer.log('FCM: Initialised successfully', name: 'FcmService');
    } catch (_) {
      developer.log(
        'FCM: Setup failed — push notifications unavailable.',
        name: 'FcmService',
      );
    }
  }

  /// Get the current FCM token (or null if not initialised / failed).
  static Future<String?> getToken() async {
    if (!_initialized) return null;
    try {
      return await _messaging.getToken();
    } catch (_) {
      return null;
    }
  }

  /// Send the registered FCM token to the backend API using Dio.
  static Future<void> registerTokenWithBackend(
    String authToken,
    String baseUrl,
    String? fcmToken,
  ) async {
    final token = fcmToken;
    if (token == null || token.isEmpty) return;

    try {
      final dio = Dio(
        BaseOptions(
          baseUrl: baseUrl,
          headers: {
            'Authorization': 'Bearer $authToken',
            'Content-Type': 'application/json',
          },
        ),
      );
      await dio.post('/api/v1/notifications/fcm-token', data: {'token': token});
      developer.log('FCM: Token registered with backend', name: 'FcmService');
    } catch (_) {
      developer.log('FCM: Token registration failed', name: 'FcmService');
    }
  }

  /// Handle a received message while the app is in the foreground.
  static void _handleForegroundMessage(RemoteMessage message) {
    final notification = message.notification;
    if (notification != null) {
      developer.log(
        'FCM: Foreground notification received',
        name: 'FcmService',
      );
      // On mobile, a local notification plugin would show the notification here.
      // On web, foreground messages are handled by the browser's service worker.
    }
  }

  /// Handle a notification tap that opens/resumes the app.
  static void _handleNotificationTap(RemoteMessage message) {
    developer.log('FCM: Notification opened', name: 'FcmService');
    // Route to the relevant page based on notification type:
    //   data['type'] == 'booking_confirmed'  => booking detail page
    //   data['type'] == 'booking_reminder'   => booking detail page
    //   data['type'] == 'review_request'     => review page
    // This will be wired when navigation routing is complete.
  }
}
