CREATE TABLE `shop_calendar_blocks` (
  `id` BIGINT NOT NULL AUTO_INCREMENT,
  `shop_id` BIGINT NOT NULL,
  `scope` VARCHAR(20) NOT NULL,
  `resource_id` BIGINT NULL,
  `purpose` VARCHAR(30) NOT NULL,
  `start_at_utc` DATETIME(3) NOT NULL,
  `end_at_utc` DATETIME(3) NOT NULL,
  `timezone` VARCHAR(100) NOT NULL,
  `reason` VARCHAR(500) NOT NULL,
  `status` VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
  `version` INTEGER NOT NULL DEFAULT 1,
  `operator_id` BIGINT NOT NULL,
  `time_off_id` BIGINT NULL,
  `maintenance_id` BIGINT NULL,
  `created_at` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updated_at` DATETIME(3) NOT NULL,
  PRIMARY KEY (`id`),
  UNIQUE INDEX `shop_calendar_blocks_time_off_id_key` (`time_off_id`),
  UNIQUE INDEX `shop_calendar_blocks_maintenance_id_key` (`maintenance_id`),
  INDEX `calendar_blocks_shop_window_idx` (`shop_id`, `status`, `start_at_utc`, `end_at_utc`),
  INDEX `calendar_blocks_resource_idx` (`shop_id`, `scope`, `resource_id`, `status`),
  CONSTRAINT `shop_calendar_blocks_shop_id_fkey` FOREIGN KEY (`shop_id`) REFERENCES `shops` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `shop_calendar_blocks_operator_id_fkey` FOREIGN KEY (`operator_id`) REFERENCES `users` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE,
  CONSTRAINT `shop_calendar_blocks_time_off_id_fkey` FOREIGN KEY (`time_off_id`) REFERENCES `therapist_time_off` (`id`) ON DELETE SET NULL ON UPDATE CASCADE,
  CONSTRAINT `shop_calendar_blocks_maintenance_id_fkey` FOREIGN KEY (`maintenance_id`) REFERENCES `room_maintenance` (`id`) ON DELETE SET NULL ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

